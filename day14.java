public class day14 {
    public static void main(String[] args) {
        // Penjumlahan dan Pengurangan 

        byte angka1 = 15;
        byte angka2 = 9;
        byte angka3 = 28;

        int total1 = angka2 + angka3;
        int total2 = total1 - angka3;
        int total3 = angka2 + angka3 - angka1;

        System.out.println("Hasil penjumlahan :\t" + total1);
        System.out.println("Hasil pengurangan :\t" + total2);
        System.out.println("TOTAL             :\t" + total3);
   
   
    }
}
